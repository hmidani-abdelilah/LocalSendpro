"""هذا الملف يشرح كيفية اكتشاف الأجهزة المتصلة بنفس الشبكة المحلية ونقل الملفات بينها باستخدام Zeroconf وTCP.

هذه الوحدة تستخدم بروتوكول Zeroconf (mDNS) لاكتشاف الأجهزة القريبة من جهازك،
ثم تستخدم مأخذ TCP لإرسال الملفات بعد أن يوافق الجهاز المستقبل على استقبالها.
كما يوفر البرنامج واجهة بسيطة عبر الطرفية تسمح للمستخدم باختيار الجهاز الهدف،
ثم اختيار الملف المراد إرساله، ومتابعة تقدم الإرسال أو الاستلام بشكل بصري.
"""

# هذا السطر يستورد مكتبة socket التي تسمح بإنشاء اتصالات شبكية TCP/IP بين أجهزة الحاسوب.
import socket

# هذا السطر يستورد مكتبة threading لتشغيل خادم الاستلام في خلفية التطبيق دون توقف واجهة المستخدم الرئيسية.
import threading

# هذا السطر يستورد مكتبة os لاستخدامها في التحقق من وجود الملف ومسار الملف الحالي داخل النظام.
import os

# هذا السطر يستورد مكتبة sys لاستخدامها في طباعة الرسائل داخل الطرفية والتحكم في شاشة التنفيذ.
import sys

# هذا السطر يستورد مكتبة select التي تسمح بانتظار إدخال المستخدم لفترة محددة دون إيقاف البرنامج بالكامل.
import select

# هذا السطر يستورد كائنات Zeroconf وServiceInfo وServiceBrowser من المكتبة zeroconf لاكتشاف الخدمات والإعلان عنها.
from zeroconf import Zeroconf, ServiceInfo, ServiceBrowser

# هذا السطر يحدد نوع الخدمة التي سيتم الإعلان عنها عبر Zeroconf ليكتشفها الأجهزة الأخرى داخل الشبكة المحلية.
SERVICE_TYPE = "_localsend._tcp.local."

# هذا السطر يحدد رقم المنفذ الذي سيستخدمه الخادم للاستقبال عبر TCP داخل الشبكة المحلية.
TCP_FILE_PORT = 50006

# هذا السطر يحصل على اسم الحاسوب الحالي من نظام التشغيل ليُستخدم كجزء من اسم الجهاز عند الإعلان عنه.
HOSTNAME = socket.gethostname()

# هذا السطر يحدّد اسم الجهاز الذي سيظهر للمستخدمين الآخرين عند اكتشافه عبر الشبكة.
DEVICE_NAME = f"Device_{HOSTNAME}"

# هذا السطر ينشئ قاموسًا فارغًا لتخزين الأجهزة المكتشفة ديناميكيًا عبر Zeroconf.
# هيكل القاموس يكون بالشكل: {service_name: {'name': ..., 'ip': ..., 'port': ...}}
discovered_devices = {}


# هذا السطر يعرّف دالة draw_progress_bar وتقبل قيمة bytes المستلمة ومجموع الحجم وطول شريط العرض.
def draw_progress_bar(received, total, length=30):
    # هذا السطر يضيف وصفًا موجزًا لوظيفة رسم شريط التقدم لسهولة الفهم عند قراءة الملف.
    """رسم شريط تقدم بصيغة رسومية أثناء استقبال أو إرسال الملف."""

    # هذا السطر يحسب نسبة التقدم الحالية بناءً على مقدار البيانات التي تم استلامها أو إرسالها.
    percent = received / total if total else 0

    # هذا السطر يحسب عدد الحروف أو الخلايا التي يجب تعبئتها داخل شريط التقدم بحسب النسبة الحالية.
    filled = int(length * percent)

    # هذا السطر يبني شريط التقدم نفسه عن طريق تكرار حرف مليء ثم حرف فارغ للجزء المتبقي.
    bar = '█' * filled + '░' * (length - filled)

    # هذا السطر يحول عدد البايتات إلى ميجابايت لعرضها بشكل إنساني في شاشة التشغيل.
    rec_mb = received / (1024 * 1024)

    # هذا السطر يحول الحجم الإجمالي إلى ميجابايت أيضًا لعرض القيم المتبقية في نفس التنسيق.
    tot_mb = total / (1024 * 1024)

    # هذا السطر يكتب شريط التقدم في نفس السطر السابق باستخدام حرف العودة إلى بداية السطر للتحديث المتكرر.
    sys.stdout.write(f"\r[{bar}] {percent * 100:.1f}% ({rec_mb:.2f}/{tot_mb:.2f} MB)")

    # هذا السطر يفرض ظهور النص فورًا في الطرفية دون تأخير عند التخزين المؤقت للإخراج.
    sys.stdout.flush()


# هذا السطر يعرّف دالة timed_input التي تنتظر إدخال المستخدم لفترة محددة ثم تعيده أو ترجع None إذا لم يحدث إدخال.
def timed_input(prompt, timeout=30):
    # هذا السطر يضيف وصفًا موجزًا للدالة ليُعرف الغرض من استخدامها عند قراءة التعليمات.
    """إرجاع إدخال المستخدم خلال فترة زمنية محددة، أو None إذا لم يتم إدخال شيء."""

    # هذا السطر يطبع رسالة السؤال في الطرفية بدون الانتقال إلى سطر جديد.
    print(prompt, end="", flush=True)

    # هذا السطر ينتظر إدخال المستخدم عبر stdin لمدة محددة بالثانية، مع عدم حظر التطبيق بالكامل.
    rlist, _, _ = select.select([sys.stdin], [], [], timeout)

    # هذا السطر يتحقق إذا كان هناك إدخال متاح فعليًا في الطرفية.
    if rlist:
        # هذا السطر يقرأ السطر المكتوب من المستخدم ثم يزيل المسافات الزائدة ويحوّله إلى أحرف صغيرة.
        return sys.stdin.readline().strip().lower()

    # هذا السطر يُرجع None إذا لم يتم إدخال أي شيء خلال المهلة المحددة.
    return None


# هذا السطر يعرّف دالة get_local_ip التي تعيد عنوان IP المحلي الذي يستخدمه الجهاز الحالي داخل الشبكة.
def get_local_ip():
    # هذا السطر يضيف وصفًا موجزًا لطبيعة هذه الدالة والغرض منها في التطبيق.
    """إرجاع عنوان IP المحلي النشط لجهاز الحاسوب الحالي لاستخدامه في الشبكة."""

    # هذا السطر ينشئ مأخذ UDP مؤقتًا فقط للحصول على عنوان IP الحقيقي للجهاز.
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)

    # هذا السطر يفتح كتلة try لمحاولة تحديد عنوان IP المحلي عبر اتصال مؤقت إلى عنوان بعيد.
    try:
        # هذا السطر يحاول الاتصال بعنوان شبكي بعيد بشكل مؤقت للحصول على عنوان IP الخاص بالجهاز الحالي.
        s.connect(('10.255.255.255', 1))

        # هذا السطر يستخرج عنوان IP الفعلي من مأخذ الاتصال المؤقت بعد نجاح الاتصال.
        ip_address = s.getsockname()[0]
    except Exception:
        # هذا السطر يلتقط أي خطأ في اكتشاف IP ويحفظ عنوان localhost كحل احتياطي.
        ip_address = '127.0.0.1'
    finally:
        # هذا السطر يغلق المقبس في جميع الحالات حتى لو فشل الاتصال أو نجح.
        s.close()

    # هذا السطر يُرجع عنوان IP الفعلي أو عنوان localhost البديل في حالة فشل اكتشافه.
    return ip_address


# هذا السطر يعرّف فئة LocalSendListener التي تقوم بمراقبة خدمات Zeroconf داخل الشبكة المحلية.
class LocalSendListener:
    # هذا السطر يضيف وصفًا موجزًا لفئة المستمع ويشرح وظيفتها الرئيسية.
    """مستمع يراقب اكتشاف أو حذف أو تحديث خدمات Zeroconf في الشبكة المحلية."""

    # هذا السطر يعرّف طريقة add_service المسؤولة عن إضافة جهاز جديد إلى القائمة عند اكتشافه.
    def add_service(self, zc, type_, name):
        # هذا السطر يضيف وصفًا للمسؤولية الأساسية لهذه الطريقة داخل الفئة.
        """تسجيل جهاز جديد من الشبكة إذا تم اكتشافه بنجاح."""

        # هذا السطر يستعلم Zeroconf عن تفاصيل الخدمة بناءً على النوع والاسم اللذين تم اكتشافهما.
        info = zc.get_service_info(type_, name)

        # هذا السطر يتحقق من أن معلومات الخدمة موجودة بالفعل قبل محاولة قراءتها.
        if info:
            # هذا السطر يحول عناوين IP من تنسيق bytes إلى نصوص قابلة للقراءة مثل "192.168.1.5".
            addresses = [socket.inet_ntoa(addr) for addr in info.addresses]

            # هذا السطر يأخذ أول عنوان IP صالح إذا كان موجودًا، أو يضع None إن لم يوجد.
            ip = addresses[0] if addresses else None

            # هذا السطر يقرأ اسم الجهاز من خصائص الخدمة (properties) إذا كان موجودًا، أو يضع Unknown كبديل.
            device_name = info.properties.get(b'device_name', b'Unknown').decode('utf-8')

            # هذا السطر يمنع إضافة الجهاز نفسه إلى قائمة الأجهزة المكتشفة تجنبًا للتكرار.
            if ip and ip != get_local_ip():
                # هذا السطر يضيف الجهاز إلى القاموس الرئيسي مع اسم الجهاز وعنوانه IP ومنفذه.
                discovered_devices[name] = {
                    'name': device_name,
                    'ip': ip,
                    'port': info.port
                }

    # هذا السطر يعرّف طريقة remove_service لإزالة جهاز من القائمة عندما يختفي من الشبكة.
    def remove_service(self, zc, type_, name):
        # هذا السطر يضيف شرحًا موجزًا لهذه الطريقة داخل الفئة.
        """إزالة جهاز من القائمة عند اختفائه من الشبكة."""

        # هذا السطر يتحقق إن كان اسم الجهاز موجودًا داخل القاموس قبل حذفه.
        if name in discovered_devices:
            # هذا السطر يحذف الجهاز من القاموس حتى لا يبقى في القائمة بعد اختفائه.
            del discovered_devices[name]

    # هذا السطر يعرّف طريقة update_service لتحديث الحالة عند تغيير خدمة أو إعادة اكتشافها.
    def update_service(self, zc, type_, name):
        # هذا السطر يضيف شرحًا لمغزى هذه الطريقة في تحديث المعلومات دون الحاجة لتكرار المنطق.
        """إعادة معالجة الخدمة عند تحديثها أو إعادة اكتشافها."""

        # هذا السطر يستدعي نفس المنطق المستخدم عند اكتشاف خدمة جديدة لتحديث القاموس.
        self.add_service(zc, type_, name)


# هذا السطر يعرّف دالة start_zeroconf_service التي تبدأ الإعلان عن هذا الجهاز واكتشاف الأجهزة الأخرى.
def start_zeroconf_service():
    # هذا السطر يضيف شرحًا واضحًا لهذا الواجب الأساسي في التطبيق في البداية.
    """تسجيل خدمة هذا الجهاز على الشبكة وبدء اكتشاف الأجهزة الأخرى عبر Zeroconf."""

    # هذا السطر يحصل على عنوان IP المحلي الحالي قبل الإعلان عن الخدمة في الشبكة.
    local_ip = get_local_ip()

    # هذا السطر ينشئ كائن Zeroconf الرئيسي المسؤول عن خدمة الإعلان والاكتشاف.
    zc = Zeroconf()

    # هذا السطر يهيئ معلومات الخدمة التي سنعلن عنها عبر بروتوكول Zeroconf داخل الشبكة المحلية.
    info = ServiceInfo(
        # هذا السطر يحدد نوع الخدمة على شكل اسم الخدمة البخاري الذي يكتشفه جميع الأجهزة.
        type_=SERVICE_TYPE,

        # هذا السطر يحدد اسم الخدمة الكامل باستخدام اسم الحاسوب الحالي واسم نوع الخدمة.
        name=f"{HOSTNAME}.{SERVICE_TYPE}",

        # هذا السطر يحدد عناوين IP المستخدمة في الإعلان، ويحول عنوان IP النصي إلى صيغة بيتية مناسبة لـ Zeroconf.
        addresses=[socket.inet_aton(local_ip)],

        # هذا السطر يحدد المنفذ الذي ستستقبل فيه هذه الخدمة طلبات الاتصال.
        port=TCP_FILE_PORT,

        # هذا السطر يضيف خاصية device_name إلى الخدمة حتى يظهر اسم الجهاز للمستلمين الآخرين.
        properties={'device_name': DEVICE_NAME},

        # هذا السطر يحدد اسم الخادم الظاهري الذي يخص هذا الجهاز داخل مجال local.
        server=f"{HOSTNAME}.local."
    )

    # هذا السطر يسجل الخدمة في كائن Zeroconfكي تصبح مرئية للأجهزة الأخرى داخل الشبكة.
    zc.register_service(info)

    # هذا السطر ينشئ كائن مستمع لالتقاط الأحداث الخاصة بظهور أو اختفاء أو تحديث الخدمات الأخرى.
    listener = LocalSendListener()

    # هذا السطر يفتح متصفّحًا لبحث الخدمات من نفس النوع، ويربطه بالمستمع الذي أنشأناه.
    browser = ServiceBrowser(zc, SERVICE_TYPE, listener)

    # هذا السطر يُرجع كائن Zeroconf نفسه ومعلومات الخدمة المسجلة حتى يمكن إلغاء التسجيل لاحقًا عند الخروج.
    return zc, info


# هذا السطر يعرّف دالة tcp_file_receiver التي تعمل كخادم TCP دائم للاستقبال من الأجهزة الأخرى.
def tcp_file_receiver():
    # هذا السطر يضيف شرحًا موجزًا لدور خادم الاستلام داخل التطبيق.
    """خادم TCP دائم الاستماع إلى طلبات استقبال الملفات من الأجهزة الأخرى."""

    # هذا السطر ينشئ مأخذ TCP جديدًا للاستماع إلى الطلبات الواردة من الأجهزة الأخرى.
    server_sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)

    # هذا السطر يضبط خيار SO_REUSEADDR حتى يسمح بإعادة استخدام المنفذ فورًا بعد إيقاف الخادم.
    server_sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)

    # هذا السطر يربط الخادم بالمنفذ المحدد ليكون جاهزًا لقبول الاتصالات على هذا الرقم.
    server_sock.bind(('', TCP_FILE_PORT))

    # هذا السطر يضع الخادم في حالة الاستماع لأكثر من اتصال في نفس الوقت.
    server_sock.listen(5)

    # هذا السطر يفتح حلقة لا نهائية للاستماع إلى الطلبات القادمة بشكل مستمر.
    while True:
        # هذا السطر يقبل اتصالًا واردًا من جهاز آخر وينتج كائن المقبس الخاص بالتواصل plus عنوان المرسل.
        client, addr = server_sock.accept()

        # هذا السطر يفتح كتلة try/catch لتجميع معالجة الطلبات حتى لو حدث خطأ ما.
        try:
            # هذا السطر يقرأ رأس الرسالة الأولي من العميل وهو نص يشرح نوع الطلب عبر الـ TCP.
            header = client.recv(1024).decode('utf-8')

            # هذا السطر يتحقق هل هذا الطلب فعلاً يطلب إرسال ملف جديد أم لا.
            if header.startswith("FILE:"):
                # هذا السطر يفصل الرأس إلى ثلاثة أجزاء: "FILE"، اسم الملف، الحجم في البايت.
                _, filename, filesize = header.split(":")

                # هذا السطر يحول قيمة الحجم إلى عدد صحيح ليتم التعامل معه في الحسابات.
                filesize = int(filesize)

                # هذا السطر يحول الحجم من بايت إلى ميجابايت لسهولة القراءة للإنسان.
                size_mb = filesize / (1024 * 1024)

                # هذا السطر يطبع رسالة توضح أن هناك طلبًا لاستلام ملف من جهاز معين.
                print(f"\n\n[!] File transfer request from {addr[0]}:")

                # هذا السطر يطبع اسم الملف المراد استلامه داخل الرسالة.
                print(f"    • File: {filename}")

                # هذا السطر يطبع حجم الملف بالميجابايت في الرسالة المعروضة.
                print(f"    • Size: {size_mb:.2f} MB")

                # هذا السطر يطلب تأكيدًا من المستخدم فيما إذا كان يرغب في قبول الملف خلال 30 ثانية.
                choice = timed_input("Do you accept the transfer? (y/n) [30 seconds]: ", timeout=30)

                # هذا السطر يتحقق ما إذا كان المستخدم قد وافق على الاستلام.
                if choice == 'y':
                    # هذا السطر يرسل رسالة ACCEPT إلى المرسل ليعرف أن الملف سيتم استلامه.
                    client.sendall("ACCEPT".encode('utf-8'))

                    # هذا السطر يطبع رسالة أن بداية الاستلام قد بدأت.
                    print("\n[*] Transfer started...\n")

                    # هذا السطر يحدد اسم الملف الذي سيتم حفظه محليًا مع بادئة received_ للتفرقة عن الملف الأصلي.
                    save_path = f"received_{os.path.basename(filename)}"

                    # هذا السطر يهيئ عدادًا لعدد البايتات المستلمة في هذه العملية.
                    received_bytes = 0

                    # هذا السطر يبدأ رسم شريط التقدم مع بداية صفرية.
                    draw_progress_bar(0, filesize)

                    # هذا السطر يفتح الملف المحلي في وضع الكتابة الثنائية لحفظ البيانات القادمة.
                    with open(save_path, 'wb') as f:
                        # هذا السطر يبدأ حلقة القراءة حتى يتم استلام كامل حجم الملف.
                        while received_bytes < filesize:
                            # هذا السطر يحسب الحجم الأقصى للكتلة التالية حتى لا يتجاوز الباقي من الملف.
                            chunk = min(4096, filesize - received_bytes)

                            # هذا السطر يستقبل جزءًا من البيانات من الشبكة إلى الذاكرة.
                            data = client.recv(chunk)

                            # هذا السطر يتحقق إذا كانت البيانات المتلقاة فارغة، ما يعني أن الاتصال انقطع.
                            if not data:
                                # هذا السطر يخرج من الحلقة إذا انقطع الاتصال.
                                break

                            # هذا السطر يكتب البيانات المستلمة داخل الملف على القرص.
                            f.write(data)

                            # هذا السطر يضيف حجم البيانات المكتوبة إلى العداد الكلي للاستلام.
                            received_bytes += len(data)

                            # هذا السطر يحدّث شريط التقدم بعد كل قطعة مستلمة.
                            draw_progress_bar(received_bytes, filesize)

                    # هذا السطر يطبع رسالة نجاح عند انتهاء الاستلام مع اسم الملف المحفوظ.
                    print(f"\n[✔] File saved to: {save_path}\n> ", end="")
                else:
                    # هذا السطر يرسل رسالة REJECT إلى المرسل إذا رفض المستخدم قبول الملف.
                    client.sendall("REJECT".encode('utf-8'))

                    # هذا السطر يطبع رسالة أن الملف قد تم رفضه بنجاح.
                    print("\n[X] File transfer rejected.\n> ", end="")
        except Exception:
            # هذا السطر يتجاهل أي خطأ يحدث أثناء التعامل مع الطلب حتى لا يتوقف الخادم.
            pass
        finally:
            # هذا السطر يغلق المقبس الحالي دائمًا بعد انتهاء الطلب بغض النظر عن النتيجة.
            client.close()


# هذا السطر يعرّف دالة send_file_to_device المسؤولة عن إرسال ملف إلى جهاز هدف محدد عبر TCP.
def send_file_to_device(target_ip, target_port, file_path):
    # هذا السطر يضيف شرحًا واضحًا لوظيفة الإرسال عند قراءة الكود.
    """إرسال ملف إلى جهاز مستهدف عبر TCP بعد التحقق من وجود الملف وتأكيد الاستلام."""

    # هذا السطر يتحقق أولاً من وجود الملف المراد إرساله على القرص قبل محاولة الإرسال.
    if not os.path.exists(file_path):
        # هذا السطر يطبع رسالة تنبيه إذا لم يوجد الملف المحدد.
        print("[!] File does not exist!")

        # هذا السطر يوقف الدالة فورًا إذا لم يوجد الملف.
        return

    # هذا السطر يزيل المسار الكامل ويستخرج فقط اسم الملف المراد إرساله.
    filename = os.path.basename(file_path)

    # هذا السطر يقيس حجم الملف الأصلي بالبايت حتى يعرف حجم البيانات المراد إرسالها.
    filesize = os.path.getsize(file_path)

    # هذا السطر ينشئ مأخذ TCP جديدًا للاتصال بالجهاز المستهدف.
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)

    # هذا السطر يضع مهلة زمنية على الاتصال حتى لا يعلق البرنامج إذا لم يرد المستلم.
    sock.settimeout(35.0)

    # هذا السطر يبدأ كتلة try لاكتشاف الأخطاء أثناء الاتصال والإرسال.
    try:
        # هذا السطر يفتح اتصال TCP مع عنوان IP والمنفذ المحددين للجهاز المستهدف.
        sock.connect((target_ip, target_port))

        # هذا السطر يكوّن الرسالة الأولية التي تحتوي على اسم الملف وحجمه لتوصيلها إلى المستلم.
        header = f"FILE:{filename}:{filesize}"

        # هذا السطر يرسل رأس الملف إلى المستلم لإعلامه بأن ملفًا قادمًا.
        sock.sendall(header.encode('utf-8'))

        # هذا السطر يطبع رسالة تفيد بأن الطلب قد تم إرساله وانتظار الرد من المستلم.
        print(f"[*] Sent request to {target_ip}. Waiting for approval...")

        # هذا السطر ينتظر استجابة المستلم، سواء ACCEPT أو REJECT.
        response = sock.recv(1024).decode('utf-8')

        # هذا السطر يتحقق إذا كانت الاستجابة ACCEPT، أي أن المستلم وافق على الاستلام.
        if response == "ACCEPT":
            # هذا السطر يطبع رسالة أن الطلب قد تم قبوله والبدء في إرفاق البيانات.
            print("[+] Request accepted! Sending data...\n")

            # هذا السطر يلغي المهلة لأننا الآن بصدد إرسال البيانات الكبيرة، لذلك لا نريد انقطاعًا غير ضروري.
            sock.settimeout(None)

            # هذا السطر يهيئ عدادًا لحساب عدد البايتات التي تم إرسالها بالفعل.
            sent_bytes = 0

            # هذا السطر يبدأ رسم شريط التقدم لإظهار نسبة الإرسال بشكل بصري.
            draw_progress_bar(0, filesize)

            # هذا السطر يفتح الملف في وضع القراءة الثنائية لتقسيمه إلى كتل قابلة للإرسال.
            with open(file_path, 'rb') as f:
                # هذا السطر يفتح حلقة غير منتهية لقراءة الملف في كتل حتى النهاية.
                while True:
                    # هذا السطر يقرأ 4096 بايت في كل مرة من الملف.
                    chunk = f.read(4096)

                    # هذا السطر يخرج من الحلقة إذا وصلت نهاية الملف.
                    if not chunk:
                        break

                    # هذا السطر يرسل الكتلة الحالية إلى الجهاز المستهدف عبر الشبكة.
                    sock.sendall(chunk)

                    # هذا السطر يضيف حجم الكتلة المرسلة إلى العداد الكلي.
                    sent_bytes += len(chunk)

                    # هذا السطر يحدّث شريط التقدم لكل كتلة ترسلها.
                    draw_progress_bar(sent_bytes, filesize)

            # هذا السطر يطبع رسالة نجاح بعد اكتمال إرسال الملف بالكامل.
            print("\n[✔] Transfer completed successfully!")
        else:
            # هذا السطر يطبع رسالة تفيد بأن المستلم رفض طلب النقل.
            print("[X] Recipient rejected the transfer.")
    except socket.timeout:
        # هذا السطر يلتقط حالة انتهاء المهلة في انتظار الرد من المستلم ويطبع تنبيهًا للمستخدم.
        print("\n[!] Timed out waiting for a response.")
    except Exception as e:
        # هذا السطر يلتقط أي خطأ آخر غير مهلة الاتصال ويطبع تفاصيل الخطأ ليعرف المستخدم سبب المشكلة.
        print(f"\n[!] Unable to connect: {e}")
    finally:
        # هذا السطر يغلق المقبس في كل الأحوال لضمان عدم ترك اتصالات مفتوحة.
        sock.close()


